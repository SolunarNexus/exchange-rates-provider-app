CREATE TABLE rates_snapshot
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date          DATE                     NOT NULL,
    base_currency VARCHAR(3)               NOT NULL,
    fetched_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_rates_snapshot_date UNIQUE (date)
);

CREATE TABLE rate
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rates_snapshot_id BIGINT         NOT NULL,
    currency          VARCHAR(3)     NOT NULL,
    rate              NUMERIC(19, 6) NOT NULL,
    CONSTRAINT fk_rate_rates_snapshot FOREIGN KEY (rates_snapshot_id) REFERENCES rates_snapshot (id),
    CONSTRAINT uq_rate_snapshot_currency UNIQUE (rates_snapshot_id, currency)
);
